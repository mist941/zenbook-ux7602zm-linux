/*
 * Emulates the UX7602 haptic touchpad (I2C HID 093A:3F01) through /dev/uhid
 * and reports whether hid-multitouch writes the haptic intensity (feature
 * report 0x09) at probe time. Prints "INTENSITY <value>" or "INTENSITY none".
 */
#include <fcntl.h>
#include <linux/uhid.h>
#include <poll.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

static const unsigned char rd[] = {
	0x05, 0x0d, 0x09, 0x05, 0xa1, 0x01,		/* Touch Pad */
	0x85, 0x04, 0x09, 0x22, 0xa1, 0x02,		/*  finger */
	0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01,
	0x09, 0x47, 0x81, 0x02, 0x09, 0x42, 0x81, 0x02,	/*   confidence, tip */
	0x95, 0x06, 0x81, 0x03,
	0x25, 0x0f, 0x75, 0x04, 0x95, 0x01, 0x09, 0x51, 0x81, 0x02,	/* contact id */
	0x81, 0x03,
	0x05, 0x01, 0x15, 0x00, 0x26, 0x1b, 0x12, 0x75, 0x10,
	0x55, 0x0e, 0x65, 0x11, 0x35, 0x00, 0x46, 0x6c, 0x03,
	0x09, 0x30, 0x95, 0x01, 0x81, 0x02,		/*   x */
	0x26, 0xb9, 0x0a, 0x46, 0x0b, 0x02, 0x09, 0x31, 0x81, 0x02, /* y */
	0xc0,
	0x05, 0x0d, 0x55, 0x0c, 0x66, 0x01, 0x10, 0x47, 0xff, 0xff, 0x00, 0x00,
	0x27, 0xff, 0xff, 0x00, 0x00, 0x75, 0x10, 0x95, 0x01, 0x09, 0x56, 0x81, 0x02,
	0x09, 0x54, 0x25, 0x7f, 0x75, 0x08, 0x81, 0x02,	/* contact count */
	0x05, 0x09, 0x09, 0x01, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
	0x95, 0x07, 0x81, 0x03,
	0x05, 0x0d, 0x85, 0x02, 0x09, 0x55, 0x09, 0x59, 0x75, 0x04, 0x95, 0x02,
	0x25, 0x0f, 0xb1, 0x02,				/* contact max, pad type */
	0x85, 0x09, 0x05, 0x0e, 0x09, 0x01, 0xa1, 0x02,	/* simple haptic controller */
	0x09, 0x23, 0x15, 0x00, 0x25, 0x64, 0x75, 0x08, 0x95, 0x01, 0xb1, 0x02,
	0xc0,
	0xc0,
	0x05, 0x0d, 0x09, 0x0e, 0xa1, 0x01,		/* input configuration */
	0x85, 0x03, 0x09, 0x22, 0xa1, 0x02,
	0x09, 0x52, 0x15, 0x00, 0x25, 0x0a, 0x75, 0x08, 0x95, 0x01, 0xb1, 0x02,
	0xc0,
	0x09, 0x22, 0xa1, 0x00, 0x85, 0x05, 0x09, 0x57, 0x09, 0x58, 0x75, 0x01,
	0x95, 0x02, 0x25, 0x01, 0xb1, 0x02, 0x95, 0x06, 0xb1, 0x03,
	0xc0,
	0xc0,
};

int main(void)
{
	struct uhid_event ev = { .type = UHID_CREATE2 };
	int fd = open("/dev/uhid", O_RDWR | O_CLOEXEC), intensity = -1, loops;

	if (fd < 0) {
		perror("uhid");
		return 2;
	}
	strcpy((char *)ev.u.create2.name, "ASUP1413 test touchpad");
	ev.u.create2.rd_size = sizeof(rd);
	ev.u.create2.bus = 0x18;
	ev.u.create2.vendor = 0x093a;
	ev.u.create2.product = 0x3f01;
	memcpy(ev.u.create2.rd_data, rd, sizeof(rd));
	if (write(fd, &ev, sizeof(ev)) != sizeof(ev)) {
		perror("create");
		return 2;
	}

	for (loops = 0; loops < 40; loops++) {
		struct pollfd p = { .fd = fd, .events = POLLIN };
		struct uhid_event in, rep = { 0 };

		if (poll(&p, 1, 50) <= 0 || read(fd, &in, sizeof(in)) <= 0)
			continue;
		if (in.type == UHID_SET_REPORT) {
			printf("  SET_REPORT id=%02x data=%02x %02x\n", in.u.set_report.rnum,
			       in.u.set_report.data[0], in.u.set_report.data[1]);
			if (in.u.set_report.rnum == 0x09)
				intensity = in.u.set_report.data[1];
			rep.type = UHID_SET_REPORT_REPLY;
			rep.u.set_report_reply.id = in.u.set_report.id;
		} else if (in.type == UHID_GET_REPORT) {
			rep.type = UHID_GET_REPORT_REPLY;
			rep.u.get_report_reply.id = in.u.get_report.id;
			rep.u.get_report_reply.size = 2;
			rep.u.get_report_reply.data[0] = in.u.get_report.rnum;
		} else {
			continue;
		}
		if (write(fd, &rep, sizeof(rep)) != sizeof(rep))
			perror("reply");
	}
	if (intensity < 0)
		printf("INTENSITY none\n");
	else
		printf("INTENSITY %d\n", intensity);
	ev.type = UHID_DESTROY;
	if (write(fd, &ev, sizeof(ev)) != sizeof(ev))
		perror("destroy");
	return 0;
}
